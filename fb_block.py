"""ลีกที่ "ปิดแจ้งเตือน" ไว้ — เว็บที่เจ้าของเล่นไม่เปิดให้แทงลีกพวกนี้

ใบเตือนของลีกที่แทงไม่ได้ = ขยะล้วนๆ ต่อให้ % สวยแค่ไหนก็ลงไม่ได้
   → ตัดทิ้งตั้งแต่ต้นทาง ทั้งตัวเฝ้าบอลสด (fb_watch) และตัวราคาคุ้ม (fb_value)

⚠️ ตัดที่ "แจ้งเตือน" เท่านั้น — ไม่แตะคลังสถิติ (fb_trust/picks.jsonl)
   เหตุผล: เลขเส้นฐานทุกลีกคิดจากคลังทั้งกอง ถ้าตัดลีกออกจากคลังด้วย
   เส้นฐานจะขยับ แล้ว % เก่ากับใหม่เทียบกันไม่ได้อีกเลย

📌 วิธีเพิ่มลีก: ดูป้ายบนการ์ด `🏆 [DE] DeW` → ใส่ `"DeW"` (หรือ `"DE/DeW"` ถ้าอยากล็อกประเทศด้วย)
   ⚠️ ใส่เป็น short_tag เท่านั้น ห้ามใส่ league_id — 1 tag คลุมหลาย id
      (`De5` = 11 id · `Cz4` = 6 id) ถ้าปิดทีละ id จะเหลือรอดมาเตือนอีก
"""

# ปิดเมื่อ 18 ส.ค. 69 ตามที่เจ้าของสั่ง — เว็บไม่เปิดให้แทง
BLOCK = [
    "DeW",   # [DE] เยอรมนี หญิง
    "De5",   # [DE] เยอรมนี ลีกภูมิภาค (Oberliga)
    "Cz4",   # [CZ] เช็ก ดิวิชั่นล่าง
]

_SET = {b.strip().upper() for b in BLOCK if b.strip()}


def blocked(m):
    """คืนชื่อลีกถ้าถูกปิดไว้ · คืน None ถ้าเตือนได้

    รับ dict คู่บอลจากฟีด Forebet (ใช้ short_tag + code เหมือนที่โชว์บนการ์ด)
    """
    tag = str((m.get("short_tag") or "")).strip()
    if not tag:
        return None                       # ไม่รู้ลีก = ไม่ตัด (fail-open ตรงนี้ถูกแล้ว
                                          # เพราะด่านลีกจริงของ fb_watch fail-closed อยู่แล้ว)
    cc = str(m.get("code") or "").strip().upper()
    if tag.upper() in _SET or f"{cc}/{tag}".upper() in _SET:
        return f"[{cc}] {tag}" if cc else tag
    return None
